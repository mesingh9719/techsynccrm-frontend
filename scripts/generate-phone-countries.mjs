// Generates src/lib/phoneCountries.ts: calling code, mobile number lengths and an example mobile per
// country, read from libphonenumber-js's full metadata so the browser bundle doesn't have to ship it.
// Run after upgrading libphonenumber-js: node scripts/generate-phone-countries.mjs
import { writeFileSync } from 'node:fs'
import { Metadata, getCountries, getExampleNumber } from 'libphonenumber-js/core'
import metadata from 'libphonenumber-js/max/metadata'
import examples from 'libphonenumber-js/mobile/examples'

const m = new Metadata(metadata)
const rows = getCountries(metadata).map((country) => {
  m.selectNumberingPlan(country)
  const plan = m.numberingPlan
  const lengths = plan.type('MOBILE')?.possibleLengths() ?? plan.possibleLengths()
  const example = getExampleNumber(country, examples, metadata)?.nationalNumber ?? ''
  return `  ${country}: ['${plan.callingCode()}', ${Math.min(...lengths)}, ${Math.max(...lengths)}, '${example}'],`
})

// The first country listed for a shared calling code is its main one (+1 → US, +44 → GB).
const mainCountries = Object.entries(metadata.country_calling_codes).map(([code, countries]) => `  '${code}': '${countries[0]}',`)

const out = `// Generated by scripts/generate-phone-countries.mjs — do not edit by hand.
// country → [calling code, min mobile digits, max mobile digits, example mobile (national number)]
export const phoneCountries: Record<string, [string, number, number, string]> = {
${rows.join('\n')}
}

// calling code → main country, for numbers pasted with a +code that several countries share
export const mainCountryByCode: Record<string, string> = {
${mainCountries.join('\n')}
}
`
writeFileSync(new URL('../src/lib/phoneCountries.ts', import.meta.url), out)
console.log(`Wrote ${rows.length} countries`)
