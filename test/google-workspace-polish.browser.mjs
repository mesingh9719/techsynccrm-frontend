// Run after google-content.browser.mjs against the local synthetic Google QA server.
import assert from 'node:assert/strict'
import fs from 'node:fs/promises'
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || '/home/butcher/.cache/ms-playwright-go/1.57.0/package/index.mjs')
const browser = await chromium.launch({ executablePath: '/usr/bin/google-chrome', args: ['--no-sandbox', '--disable-dev-shm-usage'] })
const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } }), page = await context.newPage(), errors = []
page.on('pageerror', (error) => errors.push(error.message))
const origin = process.env.QA_ORIGIN || 'http://127.0.0.1:5182'
assert(['127.0.0.1', 'localhost'].includes(new URL(origin).hostname))
try {
  const fixture = JSON.parse(await fs.readFile('/tmp/techsync-product-review-fixture.json', 'utf8'))
  const login = await context.request.post(origin + '/api/auth/login', { data: { email: fixture[0].users[0].email, password: 'FixturePassword123!' } })
  const token = (await login.json()).data.accessToken
  const get = async (path) => { const response = await context.request.get(origin + '/api' + path, { headers: { authorization: `Bearer ${token}` } }); assert(response.ok()); return (await response.json()).data }
  const company = (await get('/companies?q=Calendar%20QA%20Company&limit=10')).items[0]
  await page.goto(origin + '/app/tasks')
  await page.getByRole('button', { name: 'New task', exact: true }).click()
  const task = page.getByRole('dialog', { name: 'New task', exact: true })
  await task.getByRole('textbox', { name: /^Task/ }).fill('Keep my custom event title')
  await task.getByLabel('Type', { exact: true }).selectOption('meeting')
  await task.getByRole('button', { name: 'Schedule in Google Calendar', exact: true }).click()
  const meeting = page.getByRole('dialog', { name: 'Schedule Google meeting', exact: true })
  await meeting.getByLabel('Record type', { exact: true }).selectOption('company')
  await meeting.getByLabel('Link a company').fill(company.name)
  await page.getByRole('option', { name: company.name, exact: true }).click()
  assert.equal(await meeting.getByLabel('Meeting title').inputValue(), 'Keep my custom event title')
  await meeting.getByRole('button', { name: 'Cancel', exact: true }).click()
  await page.getByRole('dialog', { name: 'Discard unsaved changes?' }).getByRole('button', { name: 'Discard changes', exact: true }).click()
  await task.getByRole('button', { name: 'Cancel', exact: true }).click()
  await page.getByRole('dialog', { name: 'Discard unsaved changes?' }).getByRole('button', { name: 'Discard changes', exact: true }).click()
  await task.waitFor({ state: 'hidden' })
  const sheet = (await get('/google/sheets?kind=blank&status=ready')).items[0]
  await page.goto(origin + '/app/sheets?sheet=' + sheet.id)
  await page.getByLabel('Cell A1', { exact: true }).focus()
  await page.keyboard.press('Enter')
  assert.equal(await page.evaluate(() => document.activeElement.getAttribute('aria-label')), 'Cell A2')
  await page.getByLabel('Cell A50', { exact: true }).focus()
  assert.equal(await page.locator('.google-cell-address').textContent(), 'A50')
  const region = page.getByRole('region', { name: 'Spreadsheet cells' })
  const positions = await region.evaluate((root) => ({ box: root.getBoundingClientRect().toJSON(), header: root.querySelector('thead th').getBoundingClientRect().toJSON() }))
  assert(positions.header.y >= positions.box.y && positions.header.y < positions.box.y + 3)
  await page.getByRole('button', { name: 'Next rows', exact: true }).click()
  await page.getByLabel('Cell A51', { exact: true }).waitFor()
  assert.equal(await page.locator('.google-cell-address').textContent(), 'A51')
  await page.getByRole('button', { name: 'Back to spreadsheets', exact: true }).click()
  await page.getByLabel('Search spreadsheets', { exact: true }).waitFor()
  await page.setViewportSize({ width: 390, height: 844 })
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false)
  await page.screenshot({ path: '/tmp/google-content-browser/sheets-library-mobile.png' })
  await page.goto(origin + '/app/calendar')
  await page.getByLabel('Go to date', { exact: true }).fill('2027-02-06')
  const create = page.getByRole('button', { name: /^Create event on .*February 6, 2027$/ })
  const cell = create.locator('..')
  const targets = await cell.evaluate((root) => ({ day: root.querySelector('.google-day-number').getBoundingClientRect().toJSON(), add: root.querySelector('.google-day-add').getBoundingClientRect().toJSON() }))
  assert(targets.day.bottom <= targets.add.top, 'mobile date selection and create targets do not overlap')
  await cell.locator('.google-day-number').click()
  assert.equal(await page.getByRole('dialog').count(), 0)
  await create.click()
  const dated = page.getByRole('dialog', { name: 'Schedule Google meeting', exact: true })
  assert.equal(await dated.getByLabel('Starts').inputValue(), '2027-02-06T10:00')
  await dated.getByRole('button', { name: 'Cancel', exact: true }).click()
  assert.deepEqual(errors, [])
  console.log('Custom event title survives linking a company; nested draft dismissal works; Enter moves cells; row headers stay aligned; paging resets selected cell; Sheets library fits mobile; date selection and create controls do not overlap.')
} finally { await context.close(); await browser.close() }
